def _with_deltas(golden: dict, deltas: dict) -> dict:
    merged = json.loads(json.dumps(golden))
    for section, cases in deltas.items():
        merged[section].update(cases)
    return merged


EXPECTED = _with_deltas(GOLDEN, DELTAS)


class _SectionMixin:
    observed: dict

    def _check_section(self, section: str):
        expected, actual = EXPECTED[section], self.observed[section]
        self.assertEqual(sorted(expected), sorted(actual), f"{section}: scenario ids differ")
        for case_id in sorted(expected):
            with self.subTest(section=section, case=case_id):
                self.assertEqual(expected[case_id], actual[case_id])


