class TestPackageIsReadOnly(unittest.TestCase):
    WRITE_METHODS = {"insert", "upsert", "delete", "rpc", "execute", "write", "write_text", "write_bytes", "remove", "unlink"}

    def _trees(self):
        for path in sorted(PACKAGE.glob("*.py")):
            yield path, ast.parse(path.read_text(encoding="utf-8"))

    def test_no_write_style_calls(self):
        for path, tree in self._trees():
            for node in ast.walk(tree):
                if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute):
                    self.assertNotIn(node.func.attr, self.WRITE_METHODS, f"{path.name}:{node.lineno} calls .{node.func.attr}()")
                    # `.update()` on a plain name is a set/dict update; on a call chain (client.table(..).update(..)) it is a DB write
                    if node.func.attr == "update":
                        self.assertNotIsInstance(node.func.value, ast.Call, f"{path.name}:{node.lineno} chained .update()")

    def test_only_read_functions_are_imported_from_the_data_layer(self):
        for path, tree in self._trees():
            for node in ast.walk(tree):
                if isinstance(node, ast.ImportFrom) and node.module and node.module.startswith("services.supabase_service"):
                    for alias in node.names:
                        self.assertTrue(alias.name.startswith("load_"), f"{path.name}: imports non-read function {alias.name}")
                if isinstance(node, ast.ImportFrom) and node.module == "config.settings":
                    for alias in node.names:
                        self.assertFalse(alias.name.startswith(("save_", "append_")), f"{path.name}: imports {alias.name}")

    def test_package_does_not_import_the_streamlit_app(self):
        for path, tree in self._trees():
            for node in ast.walk(tree):
                if isinstance(node, ast.ImportFrom):
                    self.assertNotEqual(node.module, "streamlit_app", path.name)
                if isinstance(node, ast.Import):
                    self.assertNotIn("streamlit_app", [a.name for a in node.names], path.name)


class TestAppWiring(unittest.TestCase):
    """The shared helpers must have a single definition (in services/ask_data/helpers.py) that the app re-imports."""

    MOVED_HELPERS = [
        "_safe_int", "_safe_float", "_safe_str", "_normalize_project_name_key", "_suggest_best_project_match",
        "_invoice_category_label", "_is_paid_trial_category", "_is_new_installation_category", "_is_maintenance_category",
        "_normalize_query_text", "_normalize_project_status", "_normalize_country", "_project_license_date", "_license_status",
        "_normalize_detection_key", "_parse_detection_camera_counts", "_project_detection_counts",
        "_match_countries_from_question", "_build_invoice_answer_df", "_build_project_answer_df",
        "ORDER_STATUS_OPTIONS", "PROJECT_STATUS_OPTIONS", "DETECTION_CAMERA_FIELDS",
    ]
    MOVED_V2 = [
        "_ASK_DATA_TOOL_SPECS", "_ASK_DATA_TOOL_DESCRIPTIONS", "_resolve_project_arg", "_resolve_single_country",
        "_resolve_ask_data_arg", "_validate_ask_data_tool_call", "_camera_metric_for_project", "_filter_invoices_for_debt_tools",
        "_filter_license_entries", "_annual_payment_month", "_latest_annual_invoice_year", "_annual_license_payment_row",
        "_ask_data_tool_catalog_text", "_llm_parse_data_question",
    ]

    @classmethod
    def setUpClass(cls):
        cls.app_tree = ast.parse((ROOT / "streamlit_app.py").read_text(encoding="utf-8"))

    def _defined_in_app(self):
        names = set()
        for node in self.app_tree.body:
            if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
                names.add(node.name)
            elif isinstance(node, (ast.Assign, ast.AnnAssign)):
                targets = node.targets if isinstance(node, ast.Assign) else [node.target]
                names.update(n.id for t in targets for n in ast.walk(t) if isinstance(n, ast.Name))
        return names

    def _imported_from(self, module):
        return {a.asname or a.name for n in self.app_tree.body if isinstance(n, ast.ImportFrom) and n.module == module for a in n.names}

    def test_moved_helpers_are_imported_not_redefined(self):
        defined, imported = self._defined_in_app(), self._imported_from("services.ask_data.helpers")
        for name in self.MOVED_HELPERS:
            self.assertNotIn(name, defined, f"{name} is still defined in streamlit_app.py")
            self.assertIn(name, imported, f"{name} is not imported back into streamlit_app.py")

    def test_moved_v2_code_is_no_longer_defined_in_the_app(self):
        defined = self._defined_in_app()
        for name in self.MOVED_V2:
            if name in ("_ASK_DATA_TOOL_SPECS", "_ASK_DATA_TOOL_DESCRIPTIONS", "_validate_ask_data_tool_call",
                        "_ask_data_tool_catalog_text", "_llm_parse_data_question"):
                continue  # re-exported (imported) for backward compatibility
            self.assertNotIn(name, defined, f"{name} should live in services/ask_data only")

    def test_wrappers_delegate_to_the_package(self):
        wrappers = {n.name: n for n in self.app_tree.body if isinstance(n, ast.FunctionDef)}
        self.assertIn("_answer_data_question_smart", wrappers)
        self.assertIn("_execute_ask_data_tool", wrappers)
        for name, core in (("_answer_data_question_smart", "_ask_data_answer_smart_core"),
                           ("_execute_ask_data_tool", "_ask_data_execute_tool_core")):
            called = {c.func.id for c in ast.walk(wrappers[name]) if isinstance(c, ast.Call) and isinstance(c.func, ast.Name)}
            self.assertIn(core, called)
            self.assertLess(len(ast.unparse(wrappers[name]).splitlines()), 14, f"{name} should stay a thin wrapper")


if __name__ == "__main__":
    unittest.main()
