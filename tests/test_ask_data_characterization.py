def _with_deltas(golden: dict, deltas: dict) -> dict:
    merged = json.loads(json.dumps(golden))
    for section, cases in deltas.items():
        if isinstance(cases, dict):
            merged[section].update(cases)
        else:
            merged[section] = cases
    return merged


