-- Read-only historical state source for Ask Data's `ask_data_history` feature (default OFF). Written
-- ONLY by the standalone, scheduled `snapshot_invoice_history.py` job (never by the Streamlit app, never
-- by Ask Data itself). Purely additive: does not alter `invoices`, `projects`, `bank_payments`, or
-- `invoice_change_log` in any way.
--
-- Daily snapshot semantics:
--   * `snapshot_date` is the calendar day (UTC) the snapshot represents -- the "as of" date used to
--     answer "what was the debt on <date>" questions. Exactly one row per (snapshot_date, invoice_row_id).
--   * `captured_at` is the real UTC timestamp the job actually ran and wrote this row. A rerun for the
--     SAME `snapshot_date` (e.g. a manual re-trigger) is idempotent: it UPSERTs on
--     (snapshot_date, invoice_row_id), so the row count for that day never duplicates, but `captured_at`
--     is always overwritten with the latest run's timestamp -- the most recent write always wins for a
--     given day, and Ask Data must always display this actual `captured_at` alongside any answer that
--     uses the snapshot (never just the bare date), per the "state the actual snapshot timestamp used"
--     requirement.
--   * `country_at_capture` / `network_at_capture` are a FROZEN fallback only, computed once at capture
--     time by the SAME ProjectIndex/NetworkIndex Ask Data uses today. Historical queries resolve
--     country/network live (current resolver) by default and fall back to these frozen columns (with an
--     explicit warning) only if a project can no longer be matched live (e.g. renamed/removed since).
--
-- No secrets or bank-sensitive fields are stored (no IBAN, no raw payment text, no PDF paths).

create table if not exists invoice_snapshots (
    id                  bigint generated by default as identity primary key,
    snapshot_date       date not null,
    captured_at         timestamptz not null default timezone('utc', now()),
    invoice_row_id      bigint not null,
    invoice_number      bigint,
    project_name        text not null,
    maintenance_year    text,
    year                integer,
    for_month           text,
    invoice_type        text,
    payment_amount      numeric(12, 2) not null default 0,
    paid                text not null,
    payment_date        date,
    country_at_capture  text,
    network_at_capture  text,
    created_at          timestamptz not null default timezone('utc', now()),

    unique (snapshot_date, invoice_row_id)
);

create index if not exists invoice_snapshots_snapshot_date_idx on invoice_snapshots(snapshot_date desc);
create index if not exists invoice_snapshots_invoice_number_idx on invoice_snapshots(invoice_number);
create index if not exists invoice_snapshots_project_name_idx on invoice_snapshots(project_name);
create index if not exists invoice_snapshots_country_idx on invoice_snapshots(country_at_capture);
create index if not exists invoice_snapshots_network_idx on invoice_snapshots(network_at_capture);
create index if not exists invoice_snapshots_paid_idx on invoice_snapshots(paid);

-- Audit/idempotency log for the snapshot job itself (one row per calendar day; a rerun UPDATES the same
-- row rather than inserting a second one for that day -- "one snapshot per day" holds even under reruns).
create table if not exists invoice_snapshot_runs (
    id              bigint generated by default as identity primary key,
    snapshot_date   date not null unique,
    started_at      timestamptz not null default timezone('utc', now()),
    completed_at    timestamptz,
    row_count       integer,
    status          text not null default 'running'
                    check (status in ('running', 'success', 'failed')),
    error_message   text
);

create index if not exists invoice_snapshot_runs_snapshot_date_idx on invoice_snapshot_runs(snapshot_date desc);

alter table invoice_snapshots     enable row level security;
alter table invoice_snapshot_runs enable row level security;

