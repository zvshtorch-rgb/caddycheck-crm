-- Order confirmation tracking (Order Approvals -> Year-1 invoice + PDF + confirmation email).
--
-- NOT YET RUN. This migration is for the LIVE-mode step of the order-confirmation feature (approved
-- design, not yet wired into the "Approve" button -- see services/order_confirmation_service.py's module
-- docstring and the Order Approvals page's current "Preview order confirmation (dry run)" button, which
-- needs none of this). Do not run until live mode is explicitly approved.
--
-- Adds, to the existing purchase_orders table (migrations/create_purchase_order_approvals.sql):
--   * approved_by / approved_at           -- who/when the admin "Approve" click actually completed
--   * confirmation_invoice_number/_amount -- the Year-1 invoice this PO's confirmation is tied to
--   * confirmation_status                 -- 'none' | 'failed' | 'pending_email' | 'sent' | 'email_failed'
--   * confirmation_sent_at                -- when the confirmation email was sent
--   * confirmation_message_id             -- our own generated idempotency token (Graph's sendMail
--                                              endpoint returns no message id)
--   * confirmation_error                  -- the last error, if any, at whichever stage failed
--
-- Idempotency/duplicate-send guarantee this schema is designed for:
--   * confirmation_invoice_number is set ONLY once the Year-1 invoice has actually been committed to the
--     invoice ledger (replace_invoice_rows) -- re-clicking "Approve" after that must reuse the same
--     invoice number, never create a second invoice.
--   * confirmation_status = 'sent' is the single source of truth for "do not send again"; a "Resend
--     confirmation" action only re-attempts the email step when confirmation_status = 'email_failed',
--     never re-creates the invoice.
--
-- New order_confirmation_log table: one append-only audit row per confirmation attempt (order id,
-- approving user, timestamps, invoice number/amount, recipients, email status, message id, error) -- see
-- requirement 15 of the approved design.

alter table purchase_orders
    add column if not exists approved_by                 text,
    add column if not exists approved_at                 timestamptz,
    add column if not exists confirmation_invoice_number  text,
    add column if not exists confirmation_invoice_amount  numeric,
    add column if not exists confirmation_status          text not null default 'none'
        check (confirmation_status in ('none', 'failed', 'pending_email', 'sent', 'email_failed')),
    add column if not exists confirmation_sent_at          timestamptz,
    add column if not exists confirmation_message_id       text,
    add column if not exists confirmation_error            text;

create table if not exists order_confirmation_log (
    id                 bigint generated by default as identity primary key,
    purchase_order_id  uuid not null references purchase_orders(id) on delete cascade,
    created_at         timestamptz not null default timezone('utc', now()),
    approved_by        text,
    approved_at        timestamptz,
    invoice_number     text,
    invoice_amount     numeric,
    recipients_to      text[],
    recipients_cc      text[],
    email_status       text not null default 'pending'
        check (email_status in ('pending', 'sent', 'failed', 'skipped')),
    message_id         text,
    error_message      text
);

create index if not exists order_confirmation_log_purchase_order_id_idx
    on order_confirmation_log(purchase_order_id);

alter table order_confirmation_log enable row level security;
