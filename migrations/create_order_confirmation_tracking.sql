create or replace function public.keep_order_confirmation_identity()
returns trigger language plpgsql set search_path = public as $$
begin
    if old.confirmation_invoice_number is not null and
       new.confirmation_invoice_number is distinct from old.confirmation_invoice_number then
        raise exception 'An order confirmation invoice number is permanent';
    end if;
    if old.confirmation_pdf_base64 is not null and (
        new.confirmation_pdf_base64 is distinct from old.confirmation_pdf_base64 or
        new.confirmation_details is distinct from old.confirmation_details
    ) then raise exception 'Saved confirmation PDF/envelope is immutable'; end if;
    return new;
end; $$;
create or replace trigger purchase_orders_confirmation_identity
    before update on public.purchase_orders
    for each row execute function public.keep_order_confirmation_identity();

create or replace function public.guard_order_confirmation_invoice()
returns trigger language plpgsql set search_path = public as $$
declare owner_id text;
begin
    select description_key into owner_id from public.invoice_number_registry
        where invoice_number::text = public.invoice_number_key(new.invoice_number)
          and source = 'order-confirmation';
    if found and (new.source_purchase_order_id::text is distinct from owner_id or exists (
        select 1 from public.invoices where public.invoice_number_key(invoice_number) =
        public.invoice_number_key(new.invoice_number)
    )) then raise exception 'Order-confirmation invoice is reserved; unrelated/duplicate insert blocked'; end if;
    return new;
end; $$;
create or replace trigger invoices_order_confirmation_insert_guard
    before insert on public.invoices
    for each row execute function public.guard_order_confirmation_invoice();

-- Durable claim, deliberately WITHOUT expiry: a crash during send must never permit an automatic resend.
create or replace function public.claim_order_confirmation(
    p_order_id uuid, p_token uuid, p_expected jsonb, p_actor text, p_resend boolean
) returns jsonb language plpgsql set search_path = public as $$
declare o public.purchase_orders%rowtype;
begin
    if p_token is null or p_expected is null then raise exception 'Claim token and expected order are required'; end if;
    if nullif(trim(p_actor), '') is null then raise exception 'Approving user is required'; end if;
    select * into strict o from public.purchase_orders where id = p_order_id for update;
    if o.confirmation_status = 'sent' then return jsonb_build_object('state','sent','order',to_jsonb(o)); end if;
    if o.confirmation_lock_token is not null then
        return jsonb_build_object('state','busy','order',to_jsonb(o));
    end if;
    if not (to_jsonb(o) @> p_expected) then raise exception 'Order changed; refresh and validate again'; end if;
    if o.is_current is false or o.status not in ('pending_approval','approved') then
        raise exception 'Order is not eligible for admin approval';
    end if;
    if p_resend then
        if o.status <> 'approved' or o.confirmation_status <> 'failed'
           or o.confirmation_invoice_number is null or not o.confirmation_retry_safe
           or o.confirmation_pdf_base64 is null then
            raise exception 'Confirmation cannot be safely resent; manual review required';
        end if;
    elsif o.status <> 'pending_approval' then
        raise exception 'Approved order requires the explicit resend action';
    end if;
    if not o.confirmation_retry_safe then raise exception 'Previous send outcome is unknown; do not resend'; end if;
    if o.confirmation_invoice_number is null and exists (
        select 1 from public.invoices where source_purchase_order_id = p_order_id
    ) then raise exception 'Legacy invoice already exists for this order; review and link manually'; end if;
    update public.purchase_orders set confirmation_lock_token = p_token,
        confirmation_stage = 'preparing', confirmation_error = null
        where id = p_order_id returning * into o;
    return jsonb_build_object('state','claimed','order',to_jsonb(o));
end; $$;

create or replace function public.reserve_order_confirmation_invoice(p_order_id uuid, p_token uuid, p_actor text)
returns text language plpgsql set search_path = public as $$
declare o public.purchase_orders%rowtype; n bigint;
begin
    select * into strict o from public.purchase_orders where id = p_order_id for update;
    if p_token is null or o.confirmation_lock_token is distinct from p_token then raise exception 'Confirmation claim lost'; end if;
    if o.confirmation_invoice_number is not null then return o.confirmation_invoice_number; end if;
    -- Serialize with ordinary ledger/registry writes, including older non-RPC callers.
    lock table public.invoices in share row exclusive mode;
    lock table public.invoice_number_registry in share row exclusive mode;
    select greatest(
        coalesce((select max(public.invoice_number_key(invoice_number)::bigint) from public.invoices
                  where public.invoice_number_key(invoice_number) ~ '^[0-9]+$'), 0),
        coalesce((select max(invoice_number) from public.invoice_number_registry), 0)
    ) + 1 into n;
    insert into public.invoice_number_registry(invoice_number, source, description_key, created_by)
        values(n, 'order-confirmation', p_order_id::text, p_actor);
    update public.purchase_orders set confirmation_invoice_number = n::text where id = p_order_id;
    return n::text;
end; $$;

-- Insert-only ledger commit. Never calls destructive replace_invoice_rows / replace_invoice.
-- Existing invoice audit triggers remain active and record the insert.
create or replace function public.save_order_confirmation_invoice(
    p_order_id uuid, p_token uuid, p_rows jsonb, p_actor text
) returns jsonb language plpgsql set search_path = public as $$
declare o public.purchase_orders%rowtype; r public.invoices%rowtype; saved jsonb;
begin
    select * into strict o from public.purchase_orders where id = p_order_id for update;
    if p_token is null or o.confirmation_lock_token is distinct from p_token or o.confirmation_invoice_number is null then
        raise exception 'Confirmation claim or reserved invoice missing';
    end if;
    if o.status not in ('pending_approval','approved') or o.is_current is false then
        raise exception 'Order eligibility changed while preparing invoice';
    end if;
    lock table public.invoices in share row exclusive mode;
    lock table public.invoice_number_registry in share row exclusive mode;
    if not exists (select 1 from public.invoice_number_registry
        where invoice_number = o.confirmation_invoice_number::bigint and status = 'active'
          and source = 'order-confirmation' and description_key = p_order_id::text
    ) then raise exception 'Reserved invoice is not owned by this order'; end if;
    select coalesce(jsonb_agg(to_jsonb(i) order by i.id),'[]') into saved from public.invoices i
        where public.invoice_number_key(i.invoice_number) = o.confirmation_invoice_number;
    if jsonb_array_length(saved) > 0 then
        if jsonb_array_length(saved) <> 1 or exists (
            select 1 from jsonb_array_elements(saved) x
            where x->>'source_purchase_order_id' is distinct from p_order_id::text
               or x->>'maintenance_year' is distinct from 'Y1'
               or (x->>'payment_amount')::numeric is distinct from o.confirmation_invoice_amount
        ) then raise exception 'Unrelated or duplicate invoice rows; nothing overwritten'; end if;
        return saved;
    end if;
    if o.confirmation_invoice_amount is not null then
        raise exception 'Previously saved invoice was removed; do not recreate it';
    end if;
    if exists (select 1 from public.invoices where source_purchase_order_id = p_order_id) then
        raise exception 'A different invoice is already linked to this order';
    end if;
    if jsonb_typeof(p_rows) <> 'array' or jsonb_array_length(p_rows) <> 1 then
        raise exception 'Exactly one canonical Y1 row is required';
    end if;
    select * into r from jsonb_populate_recordset(null::public.invoices, p_rows);
    if r.invoice_number is distinct from o.confirmation_invoice_number or r.maintenance_year is distinct from 'Y1'
       or r.payment_amount is null or r.payment_amount <= 0
       or r.payment_amount::text in ('NaN','Infinity','-Infinity')
       or nullif(trim(r.project_name),'') is null or coalesce(r.paid,'') <> 'No'
       or r.payment_date is not null then raise exception 'Invalid canonical Y1 payload'; end if;
    perform set_config('caddycheck.actor', p_actor, true);
    perform set_config('caddycheck.source', 'admin-order-confirmation', true);
    insert into public.invoices(invoice_number, project_name, maintenance_year, payment_amount,
        cameras_number, payment_date, paid, year, description, invoice_type, for_month, sent_at,
        source_type, source_purchase_order_id, auto_created, auto_created_at, send_status)
    values(o.confirmation_invoice_number, r.project_name, 'Y1', r.payment_amount, r.cameras_number,
        null, 'No', r.year, r.description, r.invoice_type, r.for_month, null,
        'purchase_order', p_order_id, true, now(), 'ready_to_send')
    returning * into r;
    update public.purchase_orders set confirmation_invoice_amount = r.payment_amount,
        confirmation_stage = 'invoice_saved' where id = p_order_id;
    update public.invoice_number_registry set total_amount = r.payment_amount, ledger_saved_at = now()
        where invoice_number = o.confirmation_invoice_number::bigint;
    return jsonb_build_array(to_jsonb(r));
end; $$;

create or replace function public.start_order_confirmation_send(
    p_order_id uuid, p_token uuid, p_saved_rows jsonb, p_pdf_base64 text, p_details jsonb, p_actor text
) returns jsonb language plpgsql set search_path = public as $$
declare o public.purchase_orders%rowtype; current_rows jsonb;
begin
    select * into strict o from public.purchase_orders where id = p_order_id for update;
    if p_token is null or o.confirmation_lock_token is distinct from p_token or o.confirmation_invoice_amount is null
       or o.confirmation_stage = 'sending' then raise exception 'Invalid confirmation send claim'; end if;
    if o.status not in ('pending_approval','approved') or o.is_current is false then
        raise exception 'Order eligibility changed while rendering; do not send';
    end if;
    select coalesce(jsonb_agg(to_jsonb(i) order by i.id),'[]') into current_rows
        from (select * from public.invoices where public.invoice_number_key(invoice_number) =
              o.confirmation_invoice_number for update) i;
    if current_rows is distinct from p_saved_rows or jsonb_array_length(current_rows) <> 1 then
        raise exception 'Saved invoice changed while rendering; do not send';
    end if;
    if nullif(p_pdf_base64,'') is null or p_details->>'sender' is distinct from 'orders.caddycheck@video-inform.com'
       or coalesce(jsonb_array_length(p_details->'to'),0) = 0 then
        raise exception 'Final PDF or configured email envelope missing';
    end if;
    if o.confirmation_pdf_base64 is not null and (
        o.confirmation_pdf_base64 is distinct from p_pdf_base64 or o.confirmation_details is distinct from p_details
    ) then raise exception 'Saved confirmation PDF/envelope cannot be replaced'; end if;
    update public.purchase_orders set status = 'approved', confirmation_status = 'pending',
        approved_by = coalesce(approved_by,p_actor), approved_at = coalesce(approved_at,now()),
        confirmation_pdf_base64 = p_pdf_base64, confirmation_details = p_details,
        confirmation_stage = 'sending', confirmation_retry_safe = false
        where id = p_order_id returning * into o;
    return to_jsonb(o);
end; $$;

-- Final status and append-only audit commit in ONE transaction. A lost response cannot cause a resend.
create or replace function public.finish_order_confirmation(
    p_order_id uuid, p_token uuid, p_outcome text, p_stage text, p_error text,
    p_retry_safe boolean, p_details jsonb, p_actor text
) returns jsonb language plpgsql set search_path = public as $$
declare o public.purchase_orders%rowtype;
begin
    select * into strict o from public.purchase_orders where id = p_order_id for update;
    if exists(select 1 from public.order_confirmation_log where attempt_id = p_token and purchase_order_id = p_order_id)
        then return to_jsonb(o); end if;
    if p_token is null or o.confirmation_lock_token is distinct from p_token then raise exception 'Confirmation claim lost'; end if;
    if p_outcome is null or p_outcome not in ('sent','failed','unknown') then raise exception 'Invalid confirmation outcome'; end if;
    if p_outcome = 'sent' and o.confirmation_stage <> 'sending' then raise exception 'Email was not started'; end if;
    if p_outcome = 'sent' and (o.confirmation_pdf_base64 is null or o.status <> 'approved') then
        raise exception 'Saved confirmation PDF and approved order are required';
    end if;
    update public.purchase_orders set confirmation_status = case when p_outcome = 'sent' then 'sent' else 'failed' end,
        confirmation_sent_at = case when p_outcome = 'sent' then now() else confirmation_sent_at end,
        confirmation_error = p_error, confirmation_stage = p_stage,
        confirmation_retry_safe = (p_outcome = 'failed' and p_retry_safe),
        confirmation_lock_token = case when p_outcome = 'unknown' then p_token else null end
        where id = p_order_id returning * into o;
    insert into public.order_confirmation_log(attempt_id, purchase_order_id, approved_by, approved_at,
        invoice_number, invoice_amount, recipients_to, recipients_cc, email_status, stage, message_id, error_message)
    values(p_token, p_order_id, coalesce(o.approved_by,p_actor), o.approved_at,
        o.confirmation_invoice_number, o.confirmation_invoice_amount,
        array(select jsonb_array_elements_text(p_details->'to')),
        array(select jsonb_array_elements_text(p_details->'cc')),
        p_outcome, p_stage, null, p_error);
    return to_jsonb(o);
end; $$;

