-- Run this in the Supabase SQL editor (once).
--
-- Read-only diagnostics table for the Ask Data v2/v3 shadow comparison (editor-only v3 pilot). Never
-- contains ledger rows, invoice numbers, payment amounts/dates, raw question text, bank details or secrets
-- -- see services/ask_data/shadow.py for exactly what is (and is not) recorded. Until this table exists,
-- the app keeps working: config.settings.append_ask_data_shadow_log() falls back to a local, size-bounded
-- JSON file.
--
-- Retention: 30 days by default, pruned daily by the existing Supabase backup workflow
-- (.github/workflows/supabase-backup.yml) via scripts/prune_ask_data_shadow_log.py. Do not keep these rows
-- indefinitely -- this is a diagnostic log, not a financial record.

create table if not exists ask_data_shadow_log (
    id                     bigint generated by default as identity primary key,
    created_at             timestamptz not null default timezone('utc', now()),
    question_hash          text,                                  -- sha256-derived fingerprint; never the raw text
    question_length        integer,                               -- character count (safe, non-identifying)
    question_word_count    integer,                                -- word count (safe, non-identifying)
    editor                 text,
    primary_mode           text,                                  -- 'v2' or 'v3': which pipeline the user actually saw
    has_mismatch           boolean not null default false,
    mismatch_flags         jsonb not null default '[]'::jsonb,

    v2_outcome_kind        text,                                  -- 'tool' | 'clarification' | 'legacy' | 'none' | 'error'
    v2_tool                text,
    v2_filters             jsonb not null default '{}'::jsonb,    -- country/category/year/paid_year/paid only
    v2_project_present     boolean not null default false,
    v2_project_hash        text,                                  -- short, non-reversible fingerprint; never the name
    v2_financial           boolean not null default false,
    v2_value_display       text,                                  -- formatted total, e.g. "EUR 19,999.00"
    v2_row_count           integer,
    v2_row_set_hash        text,
    v2_clarification_asked boolean not null default false,

    v3_outcome_kind        text,                                  -- adds 'drilldown' (v2 has no such concept)
    v3_tool                text,
    v3_filters             jsonb not null default '{}'::jsonb,
    v3_project_present     boolean not null default false,
    v3_project_hash        text,
    v3_financial           boolean not null default false,
    v3_value_display       text,
    v3_row_count           integer,
    v3_row_set_hash        text,
    v3_clarification_asked boolean not null default false
);

create index if not exists ask_data_shadow_log_created_at_idx on ask_data_shadow_log(created_at desc);
create index if not exists ask_data_shadow_log_has_mismatch_idx on ask_data_shadow_log(has_mismatch) where has_mismatch;

-- Service-role only (matches every other internal log table -- see migrations/enable_rls_all_tables.sql):
-- the Streamlit CRM uses the service-role key, which bypasses RLS entirely, so this is purely a safety net
-- against the anon key (no policies added -> anon gets denied by default).
alter table ask_data_shadow_log enable row level security;
